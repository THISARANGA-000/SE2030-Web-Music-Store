        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_ORDER_ITEM_ALBUM FOREIGN KEY (AlbumID)
        REFERENCES dbo.[ALBUM] (AlbumID)
        ON DELETE NO ACTION ON UPDATE CASCADE,
    CONSTRAINT FK_ORDER_ITEM_Catalog FOREIGN KEY (CatalogID)
        REFERENCES dbo.[Catalog] (CatalogID)
        ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT CK_ORDER_ITEM_Quantity CHECK (Quantity > 0),
    CONSTRAINT CK_ORDER_ITEM_UnitPrice CHECK (UnitPrice >= 0),
    CONSTRAINT CK_ORDER_ITEM_ItemRef CHECK (
        (AlbumID IS NOT NULL AND CatalogID IS NULL) OR
        (AlbumID IS NULL AND CatalogID IS NOT NULL)
    )
);
GO

-- 3.5 PAYMENT
CREATE TABLE dbo.[PAYMENT] (
    PaymentID INT IDENTITY(1,1) NOT NULL,
    OrderID INT NOT NULL,
    PaymentDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    Amount DECIMAL(10,2) NOT NULL,
    PaymentMethod NVARCHAR(50) NOT NULL,
    TransactionReference NVARCHAR(100) NOT NULL,
    PaymentStatus NVARCHAR(20) NOT NULL DEFAULT 'Completed',
    CONSTRAINT PK_PAYMENT PRIMARY KEY CLUSTERED (PaymentID),
    CONSTRAINT UQ_PAYMENT_OrderID UNIQUE (OrderID),
    CONSTRAINT UQ_PAYMENT_TransactionRef UNIQUE (TransactionReference),
    CONSTRAINT FK_PAYMENT_ORDERS FOREIGN KEY (OrderID)
        REFERENCES dbo.[ORDERS] (OrderID)
        ON DELETE NO ACTION ON UPDATE CASCADE,
    CONSTRAINT CK_PAYMENT_Amount CHECK (Amount >= 0),
    CONSTRAINT CK_PAYMENT_Status CHECK (PaymentStatus IN ('Pending', 'Completed', 'Failed', 'Refunded'))
);
GO


-- 4. PROMOTION & FAQ MODULE

-- 4.1 PROMOTION
CREATE TABLE dbo.[PROMOTION] (
    PromotionID INT IDENTITY(1,1) NOT NULL,
    PromotionName NVARCHAR(100) NOT NULL,
    Description NVARCHAR(MAX) NULL,
    DiscountType NVARCHAR(20) NOT NULL,
    DiscountValue DECIMAL(10,2) NOT NULL,
    StartDate DATETIME2 NOT NULL,
    EndDate DATETIME2 NOT NULL,
    PromotionStatus NVARCHAR(20) NOT NULL DEFAULT 'Active',
    CONSTRAINT PK_PROMOTION PRIMARY KEY CLUSTERED (PromotionID),
    CONSTRAINT CK_PROMOTION_DiscountType CHECK (DiscountType IN ('Percentage', 'FixedAmount')),
    CONSTRAINT CK_PROMOTION_DiscountValue CHECK (DiscountValue > 0),
    CONSTRAINT CK_PROMOTION_Dates CHECK (EndDate >= StartDate),
    CONSTRAINT CK_PROMOTION_Status CHECK (PromotionStatus IN ('Active', 'Expired', 'Scheduled', 'Cancelled'))
);
GO

-- 4.2 ALBUM_PROMOTION (Junction Table)
CREATE TABLE dbo.[ALBUM_PROMOTION] (
    AlbumID INT NOT NULL,
    PromotionID INT NOT NULL,
    CONSTRAINT PK_ALBUM_PROMOTION PRIMARY KEY CLUSTERED (AlbumID, PromotionID),
    CONSTRAINT FK_ALBUM_PROMOTION_ALBUM FOREIGN KEY (AlbumID)
        REFERENCES dbo.[ALBUM] (AlbumID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_ALBUM_PROMOTION_PROMOTION FOREIGN KEY (PromotionID)
        REFERENCES dbo.[PROMOTION] (PromotionID)
        ON DELETE CASCADE ON UPDATE CASCADE
);
GO

-- 4.3 FAQ
CREATE TABLE dbo.[FAQ] (
    FAQID INT IDENTITY(1,1) NOT NULL,
    Question NVARCHAR(500) NOT NULL,
    Answer NVARCHAR(MAX) NOT NULL,
    FAQStatus NVARCHAR(20) NOT NULL DEFAULT 'Published',
    CreatedDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    UpdatedDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT PK_FAQ PRIMARY KEY CLUSTERED (FAQID),
    CONSTRAINT CK_FAQ_Status CHECK (FAQStatus IN ('Published', 'Draft', 'Archived'))
);
GO


-- 5. COMPLAINT & REVIEW MODULE


-- 5.1 COMPLAINT
CREATE TABLE dbo.[COMPLAINT] (
    ComplaintID INT IDENTITY(1,1) NOT NULL,
    ListenerID INT NOT NULL,
    Subject NVARCHAR(200) NOT NULL,
    Description NVARCHAR(MAX) NOT NULL,
    ComplaintDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    Status NVARCHAR(20) NOT NULL DEFAULT 'Open',
    Response NVARCHAR(MAX) NULL,
    ResolvedDate DATETIME2 NULL,
    CONSTRAINT PK_COMPLAINT PRIMARY KEY CLUSTERED (ComplaintID),
    CONSTRAINT FK_COMPLAINT_LISTENER FOREIGN KEY (ListenerID)
        REFERENCES dbo.[LISTENER] (ListenerID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT CK_COMPLAINT_Status CHECK (Status IN ('Open', 'In Progress', 'Resolved', 'Closed'))
);
GO

-- 5.2 REVIEW
CREATE TABLE dbo.[REVIEW] (
    ReviewID INT IDENTITY(1,1) NOT NULL,
    ListenerID INT NOT NULL,
    AlbumID INT NOT NULL,
    Rating INT NOT NULL,
    Comment NVARCHAR(MAX) NULL,
    ReviewDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    ReviewStatus NVARCHAR(20) NOT NULL DEFAULT 'Pending',
    CONSTRAINT PK_REVIEW PRIMARY KEY CLUSTERED (ReviewID),
    CONSTRAINT FK_REVIEW_LISTENER FOREIGN KEY (ListenerID)
        REFERENCES dbo.[LISTENER] (ListenerID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_REVIEW_ALBUM FOREIGN KEY (AlbumID)
        REFERENCES dbo.[ALBUM] (AlbumID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT CK_REVIEW_Rating CHECK (Rating BETWEEN 1 AND 5),
    CONSTRAINT CK_REVIEW_Status CHECK (ReviewStatus IN ('Pending', 'Approved', 'Rejected'))
);
GO


-- 6. DIGITAL LIBRARY & DOWNLOAD MODULE

-- 6.1 DIGITAL_LIBRARY
CREATE TABLE dbo.[DIGITAL_LIBRARY] (
    LibraryID INT IDENTITY(1,1) NOT NULL,
    ListenerID INT NOT NULL,
    CreatedDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    LastUpdatedDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT PK_DIGITAL_LIBRARY PRIMARY KEY CLUSTERED (LibraryID),
    CONSTRAINT UQ_DIGITAL_LIBRARY_ListenerID UNIQUE (ListenerID),
    CONSTRAINT FK_DIGITAL_LIBRARY_LISTENER FOREIGN KEY (ListenerID)
        REFERENCES dbo.[LISTENER] (ListenerID)
        ON DELETE CASCADE ON UPDATE CASCADE
);
GO

-- 6.2 LIBRARY_ITEMS
CREATE TABLE dbo.[LIBRARY_ITEMS] (
    LibraryItemID INT IDENTITY(1,1) NOT NULL,
    LibraryID INT NOT NULL,
    AlbumID INT NOT NULL,
    CatalogID INT NULL,
    AddedDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    PurchaseType NVARCHAR(50) NOT NULL DEFAULT 'Album',
    AccessStatus NVARCHAR(20) NOT NULL DEFAULT 'Active',
    CONSTRAINT PK_LIBRARY_ITEMS PRIMARY KEY CLUSTERED (LibraryItemID),
    CONSTRAINT UQ_LIBRARY_ITEMS_LibraryAlbum UNIQUE (LibraryID, AlbumID),
    CONSTRAINT FK_LIBRARY_ITEMS_DIGITAL_LIBRARY FOREIGN KEY (LibraryID)
        REFERENCES dbo.[DIGITAL_LIBRARY] (LibraryID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_LIBRARY_ITEMS_ALBUM FOREIGN KEY (AlbumID)
        REFERENCES dbo.[ALBUM] (AlbumID)
        ON DELETE NO ACTION ON UPDATE CASCADE,
    CONSTRAINT FK_LIBRARY_ITEMS_Catalog FOREIGN KEY (CatalogID)
        REFERENCES dbo.[Catalog] (CatalogID)
        ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT CK_LIBRARY_ITEMS_PurchaseType CHECK (PurchaseType IN ('Album', 'Catalog')),
    CONSTRAINT CK_LIBRARY_ITEMS_AccessStatus CHECK (AccessStatus IN ('Active', 'Revoked', 'Expired')),
    CONSTRAINT CK_LIBRARY_ITEMS_CatalogRef CHECK (
        (PurchaseType = 'Album' AND CatalogID IS NULL) OR
        (PurchaseType = 'Catalog' AND CatalogID IS NOT NULL)
    )
);
GO

-- 6.3 DOWNLOAD
CREATE TABLE dbo.[DOWNLOAD] (
    DownloadID INT IDENTITY(1,1) NOT NULL,
    LibraryItemID INT NOT NULL,
    DownloadDateTime DATETIME2 NOT NULL DEFAULT GETDATE(),
    FileFormat NVARCHAR(20) NOT NULL DEFAULT 'MP3',
    FileSize BIGINT NOT NULL,
    DownloadStatus NVARCHAR(20) NOT NULL DEFAULT 'Completed',
    CONSTRAINT PK_DOWNLOAD PRIMARY KEY CLUSTERED (DownloadID),
    CONSTRAINT FK_DOWNLOAD_LIBRARY_ITEMS FOREIGN KEY (LibraryItemID)
        REFERENCES dbo.[LIBRARY_ITEMS] (LibraryItemID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT CK_DOWNLOAD_FileSize CHECK (FileSize >= 0),
    CONSTRAINT CK_DOWNLOAD_Status CHECK (DownloadStatus IN ('Completed', 'Failed', 'Interrupted'))
);
GO

