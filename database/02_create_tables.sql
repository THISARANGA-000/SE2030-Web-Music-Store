-- 1. USER & AUTHENTICATION MODULE (Class-Table Inheritance)

-- 1.1 USER (Superclass Table)
CREATE TABLE dbo.[USER] (
    UserID INT IDENTITY(1,1) NOT NULL,
    FirstName NVARCHAR(50) NOT NULL,
    LastName NVARCHAR(50) NOT NULL,
    Email NVARCHAR(100) NOT NULL,
    PasswordHash NVARCHAR(255) NOT NULL,
    PhoneNumber NVARCHAR(20) NULL,
    RegistrationDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    AccountStatus NVARCHAR(20) NOT NULL DEFAULT 'Active',
    CONSTRAINT PK_USER PRIMARY KEY CLUSTERED (UserID),
    CONSTRAINT UQ_USER_Email UNIQUE (Email),
    CONSTRAINT CK_USER_AccountStatus CHECK (AccountStatus IN ('Active', 'Inactive', 'Suspended'))
);
GO

-- 1.2 ADMINISTRATOR (Subclass Table)
CREATE TABLE dbo.[ADMINISTRATOR] (
    AdminID INT NOT NULL,
    AdminRole NVARCHAR(50) NOT NULL DEFAULT 'Admin',
    CONSTRAINT PK_ADMINISTRATOR PRIMARY KEY CLUSTERED (AdminID),
    CONSTRAINT FK_ADMINISTRATOR_USER FOREIGN KEY (AdminID)
        REFERENCES dbo.[USER] (UserID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT CK_ADMINISTRATOR_Role CHECK (AdminRole IN ('SuperAdmin', 'StoreManager', 'SalesManager', 'CustomerSupport', 'CatalogCoordinator'))
);
GO

-- 1.3 LISTENER (Subclass Table)
CREATE TABLE dbo.[LISTENER] (
    ListenerID INT NOT NULL,
    CONSTRAINT PK_LISTENER PRIMARY KEY CLUSTERED (ListenerID),
    CONSTRAINT FK_LISTENER_USER FOREIGN KEY (ListenerID)
        REFERENCES dbo.[USER] (UserID)
        ON DELETE CASCADE ON UPDATE CASCADE
);
GO

-- 2. ARTIST, GENRE & MUSIC CATALOG MODULE

-- 2.1 ARTIST
CREATE TABLE dbo.[ARTIST] (
    ArtistID INT IDENTITY(1,1) NOT NULL,
    ArtistName NVARCHAR(100) NOT NULL,
    Biography NVARCHAR(MAX) NULL,
    Country NVARCHAR(50) NULL,
    CONSTRAINT PK_ARTIST PRIMARY KEY CLUSTERED (ArtistID)
);
GO

-- 2.2 GENRE
CREATE TABLE dbo.[GENRE] (
    GenreID INT IDENTITY(1,1) NOT NULL,
    GenreName NVARCHAR(50) NOT NULL,
    Description NVARCHAR(255) NULL,
    CONSTRAINT PK_GENRE PRIMARY KEY CLUSTERED (GenreID),
    CONSTRAINT UQ_GENRE_GenreName UNIQUE (GenreName)
);
GO

-- 2.3 Catalog
CREATE TABLE dbo.[Catalog] (
    CatalogID INT IDENTITY(1,1) NOT NULL,
    CatalogName NVARCHAR(100) NOT NULL,
    Description NVARCHAR(MAX) NULL,
    Price DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    CreatedDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT PK_Catalog PRIMARY KEY CLUSTERED (CatalogID),
    CONSTRAINT CK_Catalog_Price CHECK (Price >= 0)
);
GO

-- 2.4 ALBUM
CREATE TABLE dbo.[ALBUM] (
    AlbumID INT IDENTITY(1,1) NOT NULL,
    AlbumTitle NVARCHAR(150) NOT NULL,
    ReleaseDate DATE NULL,
    AlbumStatus NVARCHAR(20) NOT NULL DEFAULT 'Available',
    Price DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    Description NVARCHAR(MAX) NULL,
    CoverImageURL NVARCHAR(255) NULL,
    ArtistID INT NOT NULL,
    GenreID INT NOT NULL,
    CatalogID INT NULL,
    CONSTRAINT PK_ALBUM PRIMARY KEY CLUSTERED (AlbumID),
    CONSTRAINT FK_ALBUM_ARTIST FOREIGN KEY (ArtistID)
        REFERENCES dbo.[ARTIST] (ArtistID)
        ON DELETE NO ACTION ON UPDATE CASCADE,
    CONSTRAINT FK_ALBUM_GENRE FOREIGN KEY (GenreID)
        REFERENCES dbo.[GENRE] (GenreID)
        ON DELETE NO ACTION ON UPDATE CASCADE,
    CONSTRAINT FK_ALBUM_Catalog FOREIGN KEY (CatalogID)
        REFERENCES dbo.[Catalog] (CatalogID)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT CK_ALBUM_Price CHECK (Price >= 0),
    CONSTRAINT CK_ALBUM_AlbumStatus CHECK (AlbumStatus IN ('Available', 'Unavailable', 'ComingSoon', 'Discontinued'))
);
GO

-- 2.5 TRACK (Weak Entity)
CREATE TABLE dbo.[TRACK] (
    TrackID INT IDENTITY(1,1) NOT NULL,
    AlbumID INT NOT NULL,
    TrackTitle NVARCHAR(150) NOT NULL,
    TrackNumber INT NOT NULL,
    Duration INT NOT NULL,
    AudioFileURL NVARCHAR(255) NOT NULL,
    CONSTRAINT PK_TRACK PRIMARY KEY CLUSTERED (TrackID),
    CONSTRAINT FK_TRACK_ALBUM FOREIGN KEY (AlbumID)
        REFERENCES dbo.[ALBUM] (AlbumID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT UQ_TRACK_AlbumTrackNumber UNIQUE (AlbumID, TrackNumber),
    CONSTRAINT CK_TRACK_Duration CHECK (Duration > 0),
    CONSTRAINT CK_TRACK_TrackNumber CHECK (TrackNumber > 0)
);
GO


-- 3. SHOPPING CART & ORDER / SALES MANAGEMENT MODULE


-- 3.1 CART
CREATE TABLE dbo.[CART] (
    CartID INT IDENTITY(1,1) NOT NULL,
    ListenerID INT NOT NULL,
    CreatedDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    LastUpdatedDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    CartStatus NVARCHAR(20) NOT NULL DEFAULT 'Active',
    CONSTRAINT PK_CART PRIMARY KEY CLUSTERED (CartID),
    CONSTRAINT UQ_CART_ListenerID UNIQUE (ListenerID),
    CONSTRAINT FK_CART_LISTENER FOREIGN KEY (ListenerID)
        REFERENCES dbo.[LISTENER] (ListenerID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT CK_CART_CartStatus CHECK (CartStatus IN ('Active', 'Abandoned', 'Converted'))
);
GO

-- 3.2 CART_ITEM (Weak Entity)
CREATE TABLE dbo.[CART_ITEM] (
    CartID INT NOT NULL,
    ItemNo INT NOT NULL,
    AlbumID INT NULL,
    CatalogID INT NULL,
    Quantity INT NOT NULL DEFAULT 1,
    UnitPrice DECIMAL(10,2) NOT NULL,
    AddedDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    CONSTRAINT PK_CART_ITEM PRIMARY KEY CLUSTERED (CartID, ItemNo),
    CONSTRAINT FK_CART_ITEM_CART FOREIGN KEY (CartID)
        REFERENCES dbo.[CART] (CartID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT FK_CART_ITEM_ALBUM FOREIGN KEY (AlbumID)
        REFERENCES dbo.[ALBUM] (AlbumID)
        ON DELETE NO ACTION ON UPDATE CASCADE,
    CONSTRAINT FK_CART_ITEM_Catalog FOREIGN KEY (CatalogID)
        REFERENCES dbo.[Catalog] (CatalogID)
        ON DELETE NO ACTION ON UPDATE NO ACTION,
    CONSTRAINT CK_CART_ITEM_Quantity CHECK (Quantity > 0),
    CONSTRAINT CK_CART_ITEM_UnitPrice CHECK (UnitPrice >= 0),
    CONSTRAINT CK_CART_ITEM_ItemRef CHECK (
        (AlbumID IS NOT NULL AND CatalogID IS NULL) OR
        (AlbumID IS NULL AND CatalogID IS NOT NULL)
    )
);
GO

-- 3.3 ORDERS
CREATE TABLE dbo.[ORDERS] (
    OrderID INT IDENTITY(1,1) NOT NULL,
    ListenerID INT NOT NULL,
    OrderDate DATETIME2 NOT NULL DEFAULT GETDATE(),
    OrderStatus NVARCHAR(20) NOT NULL DEFAULT 'Pending',
    TotalAmount DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    CONSTRAINT PK_ORDERS PRIMARY KEY CLUSTERED (OrderID),
    CONSTRAINT FK_ORDERS_LISTENER FOREIGN KEY (ListenerID)
        REFERENCES dbo.[LISTENER] (ListenerID)
        ON DELETE NO ACTION ON UPDATE CASCADE,
    CONSTRAINT CK_ORDERS_TotalAmount CHECK (TotalAmount >= 0),
    CONSTRAINT CK_ORDERS_OrderStatus CHECK (OrderStatus IN ('Pending', 'Processing', 'Completed', 'Cancelled', 'Refunded'))
);
GO

-- 3.4 ORDER_ITEM (Weak Entity)
CREATE TABLE dbo.[ORDER_ITEM] (
    OrderID INT NOT NULL,
    ItemNo INT NOT NULL,
    AlbumID INT NULL,
    CatalogID INT NULL,
